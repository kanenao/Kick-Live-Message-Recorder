import assert from "node:assert/strict";
import {supportTargetGroups} from "../electron/ranking-support-targets.ts";
import {SUPPORT_TARGET_LIMIT,supportFeedState} from "../electron/ranking-support-policy.ts";
import {readFileSync} from "node:fs";
const top=Array.from({length:20},(_,i)=>"c"+i);
const first=supportTargetGroups(top,[]);
assert.equal(SUPPORT_TARGET_LIMIT,20);
assert.deepEqual(first.map(g=>g.length),[5,5,5,5]);
assert.equal(new Set(first.flat()).size,20);
assert.deepEqual(first[0],[...top.slice(0,5)].sort());
assert.deepEqual(supportTargetGroups([...top].reverse(),first),first);
const changed=supportTargetGroups([...top.slice(0,19),"new"],first);
assert.deepEqual(changed.slice(0,3),first.slice(0,3));
assert.ok(changed[3].includes("new"));assert.ok(!changed.flat().includes("c19"));
assert.deepEqual(supportTargetGroups([],first),[[],[],[],[]]);
assert.equal(supportTargetGroups([...top,"extra"],first).flat().length,20);
assert.deepEqual(supportTargetGroups(["bad!","a","a","b"],[]),[["a","b"],[],[],[]]);
assert.equal(supportFeedState(false,null),"outside");
assert.equal(supportFeedState(false,1000),"outside");
assert.equal(supportFeedState(true,null),"waiting");
assert.equal(supportFeedState(true,1000),"subscribed");
const main=readFileSync(new URL("../electron/main.ts",import.meta.url),"utf8");
const ui=readFileSync(new URL("../src/ui/KickRanking.tsx",import.meta.url),"utf8");
assert.ok(main.includes("length:SUPPORT_GROUP_COUNT"));
assert.ok(main.includes("slice(0,SUPPORT_TARGET_LIMIT)"));
assert.ok(main.includes("if(!target)return []"));
assert.ok(ui.includes("購読済・観測待ち"));
assert.ok(ui.includes("購読待ち・再試行"));
assert.ok(ui.includes("監視対象外"));
console.log("応援監視：20配信、5配信×4接続、購読状態、対象外、上限と停止");
