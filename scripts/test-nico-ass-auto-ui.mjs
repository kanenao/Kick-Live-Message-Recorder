assert.ok(ui.includes("autoFlow: settings.assAutoFlow"), "過去配信ASS・コメント付き動画の両方へ設定を送る");
assert.ok(encoder.includes("reserveNicoAssLane("), "動画生成の字幕配置に自動レーン計算を利用");
