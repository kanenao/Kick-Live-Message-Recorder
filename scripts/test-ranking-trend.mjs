import assert from "node:assert/strict";
import {appendTrendFrame,rankTrendPoints,rankTrendSegments} from "../electron/ranking-trend.ts";
const start="2026-11-26T00:00:00Z",at=Date.parse(start);
const frame=(offset,rank,session=start,complete=true)=>({at:new Date(at+offset).toISOString(),scope:"ja",complete,full:complete,starts:new Map([["a",session]]),ranks:{viewers:new Map(rank===null?[]:[["a",rank]])}});
let h={};
for(let i=0;i<4;i++)h=appendTrendFrame(h,frame(i*10000,[1,3,1,1][i]),["viewers"]);
assert.equal(h.viewers.length,4);
assert.equal(appendTrendFrame(h,frame(30000,4),["viewers"]),h);
const p=rankTrendPoints(h.viewers,"viewers","a",start);
assert.deepEqual(p.map(v=>v.rank),[1,3,1,1]);
assert.equal(rankTrendSegments(p).length,1);
assert.match(rankTrendSegments(p)[0],/^3\.00,3\.00 /);
assert.deepEqual(rankTrendSegments([p[0],{...p[1],rank:null},p[2]]),[]);
assert.deepEqual(rankTrendSegments([p[0],{...p[1],at:at+40000}]),[]);
assert.equal(rankTrendPoints([frame(0,1,start,false)],"viewers","a",start)[0].rank,null);
assert.deepEqual(rankTrendPoints(h.viewers,"viewers","a","2026-11-26T01:00:00Z"),[]);
for(let i=4;i<100;i++)h=appendTrendFrame(h,frame(i*10000,1),["viewers"]);
assert.equal(h.viewers.length,60);
console.log("rank trend: duplicate, session, missing data, gap, direction and bounded history OK");

const missing={...frame(10000,1),starts:new Map(),ranks:{viewers:new Map()}};
const gapped=rankTrendPoints([frame(0,1),missing,frame(20000,2)],"viewers","a",start);
assert.deepEqual(gapped.map(p=>p.rank),[1,null,2]);
assert.deepEqual(rankTrendSegments(gapped),[]);
const restarted=rankTrendPoints([frame(0,1),frame(10000,2,"2026-11-26T00:00:10Z")],"viewers","a",start);
assert.deepEqual(restarted.map(p=>p.rank),[1,null]);
assert.deepEqual(rankTrendPoints([missing,frame(20000,2)],"viewers","a",start).map(p=>p.rank),[2]);
console.log("rank trend: missing row and session changes remain explicit gaps");
