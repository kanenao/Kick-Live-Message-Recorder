import assert from "node:assert/strict";
import {captureRankingScroll,restoreRankingScroll} from "../src/shared/ranking-scroll.ts";
import {readFileSync} from "node:fs";
const cards=[{slug:"a",top:-120,bottom:-10},{slug:"b",top:-10,bottom:100},{slug:"c",top:100,bottom:210}];
const saved=captureRankingScroll(500,800,cards);
assert.deepEqual(saved,{y:500,anchor:"b",offset:-10});
assert.equal(restoreRankingScroll(saved,0,[{slug:"b",top:350}],1000),360);
assert.equal(restoreRankingScroll(saved,100,[{slug:"b",top:250}],1000),360);
assert.equal(restoreRankingScroll(saved,0,[{slug:"c",top:350}],1000),500);
assert.equal(restoreRankingScroll(saved,0,[],300),300);
assert.deepEqual(captureRankingScroll(0,800,cards),{y:0,anchor:null,offset:0});
assert.equal(restoreRankingScroll(captureRankingScroll(0,800,cards),0,cards,1000),0);
assert.equal(restoreRankingScroll(saved,0,[{slug:"b",top:-100}],1000),0);
assert.equal(captureRankingScroll(150,800,[{slug:"x",top:900,bottom:1000}]).anchor,null);
const app=readFileSync(new URL("../src/ui/App.tsx",import.meta.url),"utf8");
const ui=readFileSync(new URL("../src/ui/KickRanking.tsx",import.meta.url),"utf8");
assert.ok(app.includes('if(tab==="ranking"){'));
assert.ok(app.includes('rankingScroll.current=captureRankingScroll'));
assert.ok(app.includes('const target=restoreRankingScroll'));
assert.ok(app.includes('window.scrollTo({top:target,behavior:"instant"})'));
assert.ok(ui.includes('data-ranking-slug={row.slug}'));
assert.ok(ui.includes('pageVisible&&auto&&configured&&desktop'));
console.log("ランキングのスクロール復元・順位移動・対象消失・範囲制限");
