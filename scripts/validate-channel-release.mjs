import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const directory = process.argv[2] || "release";
const version = pkg.version;
const channel = version.includes("-beta.") ? "beta" : "latest";
assert.ok(/^\d+\.\d+\.\d+(?:-beta\.\d+)?$/.test(version), "Unexpected release version");
const files = readdirSync(directory);
const exe = "Kick-Live-Message-Recorder-Setup-" + version + ".exe";
assert.deepEqual(files.filter(f=>f.endsWith(".exe")), [exe], "Unexpected exe asset name");
assert.equal(pkg.build.nsis.artifactName, "Kick-Live-Message-Recorder-Setup-${version}.${ext}");
const expectedManifest = channel + ".yml";
assert.ok(files.includes(expectedManifest), "Missing channel update manifest");
assert.ok(!files.includes(channel==="beta" ? "latest.yml" : "beta.yml"), "Do not mix update channels");
const size = statSync(join(directory, exe)).size;
assert.ok(size > 100000, "Missing or truncated Windows installer");
const hash = createHash("sha512");
for await (const chunk of createReadStream(join(directory, exe))) hash.update(chunk);
const digest = hash.digest("base64");
const meta = readFileSync(join(directory, expectedManifest), "utf8");
assert.match(meta, new RegExp("^version:\\s*" + version.replace(/[.]/g, "\\.") + "\\s*$", "m"));
const url = meta.match(/^\s*-\s*url:\s*(.+?)\s*$/m)?.[1]?.replace(/^["']|["']$/g, "");
assert.equal(decodeURIComponent(url || ""), exe, "Manifest URL and uploaded exe disagree (404 risk)");
const shaValues = [...meta.matchAll(/^\s*sha512:\s*(\S+)\s*$/gm)].map(m=>m[1]);
assert.ok(shaValues.length>0 && shaValues.every(s=>s===digest), "Manifest SHA512 does not match installer");
const declaredSize = Number(meta.match(/^\s*size:\s*(\d+)\s*$/m)?.[1]||size);
assert.equal(declaredSize,size, "Manifest installer size mismatch");
console.log("Windows更新ファイル検証成功：",channel,version,exe,size);
